using System;
using OpenTK.Graphics.OpenGL4;
using OpenTK.Mathematics;
using OpenTK.Windowing.Common;
using OpenTK.Windowing.Desktop;
using OpenTK.Windowing.GraphicsLibraryFramework;

using GtaEditor.Input;
using GtaEditor.Scene;
using GtaEditor.Rendering;
using GtaEditor.UI;

namespace GtaEditor.Core
{
    /// <summary>
    /// Главное окно GTA SA Map Editor.
    ///
    /// Отвечает за:
    /// - создание OpenGL-сцены;
    /// - камеру;
    /// - обработку клавиатуры и мыши;
    /// - рендеринг сцены;
    /// - пользовательский интерфейс редактора;
    /// - изменение размеров окна.
    /// </summary>
    public unsafe class EditorWindow : GameWindow
    {
        // ============================================================
        // КОМПОНЕНТЫ РЕДАКТОРА
        // ============================================================

        /// <summary>
        /// Свободная 3D-камера.
        /// </summary>
        private CameraController? _camera;

        /// <summary>
        /// Сетка 3D-сцены.
        /// </summary>
        private EditorGrid? _grid;

        /// <summary>
        /// OpenGL shader.
        /// </summary>
        private ShaderProgram? _shader;

        /// <summary>
        /// Пользовательский интерфейс редактора.
        /// </summary>
        private EditorUI? _ui;


        // ============================================================
        // УПРАВЛЕНИЕ КАМЕРОЙ
        // ============================================================

        /// <summary>
        /// Флаг активного управления камерой.
        ///
        /// true:
        /// RMB зажат и мышь управляет обзором.
        /// </summary>
        private bool _cameraControlActive;


        /// <summary>
        /// Центр окна.
        ///
        /// При управлении камерой курсор постоянно
        /// возвращается в эту точку.
        /// </summary>
        private Vector2 _cameraCenter;


        // ============================================================
        // CONSTRUCTOR
        // ============================================================

        public EditorWindow(
            GameWindowSettings gameWindowSettings,
            NativeWindowSettings nativeWindowSettings)
            : base(
                gameWindowSettings,
                nativeWindowSettings)
        {
            // Заголовок окна.
            Title = "GTA SA Map Editor";

            // При запуске курсор обычный и видимый.
            CursorState = CursorState.Normal;
        }


        // ============================================================
        // ON LOAD
        // ============================================================

        protected override void OnLoad()
        {
            base.OnLoad();


            // ========================================================
            // OPENGL
            // ========================================================

            // Цвет фона редактора.
            GL.ClearColor(
                new Color4(
                    0.15f,
                    0.15f,
                    0.18f,
                    1.0f
                )
            );


            // Включаем Z-буфер.
            //
            // Он нужен для правильной отрисовки 3D-объектов.
            GL.Enable(
                EnableCap.DepthTest
            );


            // ========================================================
            // CAMERA
            // ========================================================

            // Создаём свободную камеру.
            _camera =
                new CameraController();


            // ========================================================
            // SHADER
            // ========================================================

            // Загружаем vertex + fragment shader.
            _shader =
                new ShaderProgram(
                    "GTAMapEditor.Assets.shader.vert",
                    "GTAMapEditor.Assets.shader.frag"
                );


            // ========================================================
            // GRID
            // ========================================================

            // Создаём мировую сетку.
            //
            // size:
            // количество ячеек.
            //
            // step:
            // размер одной ячейки.
            _grid =
                new EditorGrid(
                    size: 200,
                    step: 1.0f
                );


            // ========================================================
            // UI
            // ========================================================

            // Создаём пользовательский интерфейс.
            //
            // WindowHandle — настоящее HWND окно OpenTK.
            //
            // EditorUI использует его как родительское окно
            // для своих элементов интерфейса.
            _ui = new EditorUI((IntPtr)WindowPtr);


            // ========================================================
            // ЦЕНТР ОКНА
            // ========================================================

            // Рассчитываем центр окна.
            _cameraCenter =
                new Vector2(
                    Size.X / 2.0f,
                    Size.Y / 2.0f
                );


            // ========================================================
            // НАСТРОЙКА UI
            // ========================================================

            // Передаём UI текущий размер окна.
            _ui.Resize(
                Size.X,
                Size.Y
            );


            // ========================================================
            // OPENGL VIEWPORT
            // ========================================================

            GL.Viewport(
                0,
                0,
                Size.X,
                Size.Y
            );
        }


        // ============================================================
        // UPDATE FRAME
        // ============================================================

        protected override void OnUpdateFrame(
            FrameEventArgs args)
        {
            base.OnUpdateFrame(args);


            // Если камера ещё не создана,
            // дальше выполнять код нельзя.
            if (_camera == null)
            {
                return;
            }


            // Время текущего кадра.
            //
            // Например:
            // 0.016 = примерно 60 FPS.
            float deltaTime =
                (float)args.Time;


            // ========================================================
            // RMB
            // ========================================================

            bool rightMouseDown =
                MouseState.IsButtonDown(
                    MouseButton.Right
                );


            // ========================================================
            // НАЖАТИЕ RMB
            // ========================================================

            if (
                rightMouseDown &&
                !_cameraControlActive)
            {
                StartCameraControl();
            }


            // ========================================================
            // ОТПУСКАНИЕ RMB
            // ========================================================

            if (
                !rightMouseDown &&
                _cameraControlActive)
            {
                StopCameraControl();
            }


            // ========================================================
            // УПРАВЛЕНИЕ КАМЕРОЙ
            // ========================================================

            if (_cameraControlActive)
            {
                UpdateCameraControl(
                    deltaTime
                );
            }


            // ========================================================
            // F — ВОЗВРАТ К НАЧАЛЬНОЙ ПОЗИЦИИ
            // ========================================================

            if (
                KeyboardState.IsKeyPressed(
                    Keys.F
                )
            )
            {
                _camera.SetPosition(
                    new Vector3(
                        0.0f,
                        5.0f,
                        10.0f
                    )
                );
            }
        }


        // ============================================================
        // START CAMERA CONTROL
        // ============================================================

        /// <summary>
        /// Включает управление камерой.
        ///
        /// Вызывается в момент нажатия RMB.
        /// </summary>
        private void StartCameraControl()
        {
            _cameraControlActive = true;


            // ========================================================
            // ЦЕНТР ОКНА
            // ========================================================

            _cameraCenter =
                new Vector2(
                    Size.X / 2.0f,
                    Size.Y / 2.0f
                );


            // ========================================================
            // СКРЫВАЕМ КУРСОР
            // ========================================================

            CursorState =
                CursorState.Hidden;


            // ========================================================
            // СТАВИМ МЫШЬ В ЦЕНТР
            // ========================================================

            MousePosition =
                _cameraCenter;
        }


        // ============================================================
        // STOP CAMERA CONTROL
        // ============================================================

        /// <summary>
        /// Выключает управление камерой.
        ///
        /// Вызывается после отпускания RMB.
        /// </summary>
        private void StopCameraControl()
        {
            _cameraControlActive = false;


            // Возвращаем обычный курсор.
            CursorState =
                CursorState.Normal;
        }


        // ============================================================
        // UPDATE CAMERA CONTROL
        // ============================================================

        /// <summary>
        /// Обрабатывает свободный полёт камеры.
        ///
        /// RMB:
        /// вращение мышью.
        ///
        /// WASD:
        /// перемещение.
        ///
        /// Q/E:
        /// вертикальное перемещение.
        ///
        /// Shift:
        /// ускорение.
        ///
        /// Ctrl:
        /// замедление.
        ///
        /// Колесо:
        /// изменение скорости полёта.
        /// </summary>
        private void UpdateCameraControl(
            float deltaTime)
        {
            if (_camera == null)
            {
                return;
            }


            // ========================================================
            // ТЕКУЩАЯ ПОЗИЦИЯ МЫШИ
            // ========================================================

            Vector2 mousePosition =
                MousePosition;


            // ========================================================
            // ОТКЛОНЕНИЕ ОТ ЦЕНТРА
            // ========================================================

            float deltaX =
                mousePosition.X -
                _cameraCenter.X;


            float deltaY =
                mousePosition.Y -
                _cameraCenter.Y;


            // ========================================================
            // ВРАЩЕНИЕ КАМЕРЫ
            // ========================================================

            if (
                MathF.Abs(deltaX) > 0.001f ||
                MathF.Abs(deltaY) > 0.001f
            )
            {
                _camera.Look(
                    deltaX,
                    deltaY
                );
            }


            // ========================================================
            // ВОЗВРАЩАЕМ МЫШЬ В ЦЕНТР
            // ========================================================

            MousePosition =
                _cameraCenter;


            // ========================================================
            // ДВИЖЕНИЕ WASD + Q/E
            // ========================================================

            _camera.Move(
                KeyboardState,
                deltaTime
            );


            // ========================================================
            // КОЛЕСО МЫШИ
            // ========================================================

            float scroll =
                MouseState.ScrollDelta.Y;


            if (
                MathF.Abs(scroll) > 0.001f
            )
            {
                _camera.ChangeMoveSpeed(
                    scroll
                );
            }
        }


        // ============================================================
        // RENDER FRAME
        // ============================================================

        protected override void OnRenderFrame(
            FrameEventArgs args)
        {
            base.OnRenderFrame(args);


            // Проверяем необходимые компоненты.
            if (
                _camera == null ||
                _shader == null ||
                _grid == null
            )
            {
                return;
            }


            // ========================================================
            // CLEAR
            // ========================================================

            // Очищаем цветовой буфер
            // и буфер глубины.
            GL.Clear(
                ClearBufferMask.ColorBufferBit |
                ClearBufferMask.DepthBufferBit
            );


            // ========================================================
            // ASPECT RATIO
            // ========================================================

            float aspectRatio =
                Size.Y > 0
                    ? Size.X / (float)Size.Y
                    : 1.0f;


            // ========================================================
            // PROJECTION
            // ========================================================

            // Перспективная камера.
            //
            // 60 градусов:
            // угол обзора.
            //
            // 0.1:
            // минимальная видимая дистанция.
            //
            // 10000:
            // максимальная видимая дистанция.
            Matrix4 projection =
                Matrix4.CreatePerspectiveFieldOfView(
                    MathHelper.DegreesToRadians(
                        60.0f
                    ),

                    aspectRatio,

                    0.1f,

                    10000.0f
                );


            // ========================================================
            // SHADER
            // ========================================================

            _shader.Use();


            // Передаём матрицу камеры.
            _shader.SetMatrix4(
                "view",
                _camera.ViewMatrix
            );


            // Передаём перспективу.
            _shader.SetMatrix4(
                "projection",
                projection
            );


            // ========================================================
            // GRID
            // ========================================================

            _grid.Draw(
                _shader
            );


            // ========================================================
            // SWAP BUFFERS
            // ========================================================

            SwapBuffers();
        }


        // ============================================================
        // RESIZE
        // ============================================================

        protected override void OnResize(
            ResizeEventArgs e)
        {
            base.OnResize(e);


            // ========================================================
            // OPENGL VIEWPORT
            // ========================================================

            GL.Viewport(
                0,
                0,
                Size.X,
                Size.Y
            );


            // ========================================================
            // ЦЕНТР КАМЕРЫ
            // ========================================================

            _cameraCenter =
                new Vector2(
                    Size.X / 2.0f,
                    Size.Y / 2.0f
                );


            // ========================================================
            // UI
            // ========================================================

            _ui?.Resize(
                Size.X,
                Size.Y
            );
        }


        // ============================================================
        // UNLOAD
        // ============================================================

        protected override void OnUnload()
        {
            // ========================================================
            // UI
            // ========================================================

            _ui?.Dispose();

            _ui = null;


            // ========================================================
            // GRID
            // ========================================================

            _grid?.Dispose();

            _grid = null;


            // ========================================================
            // SHADER
            // ========================================================

            _shader?.Dispose();

            _shader = null;


            // ========================================================
            // BASE
            // ========================================================

            base.OnUnload();
        }
    }
}